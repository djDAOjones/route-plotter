#!/usr/bin/env node
// Directory inventory from Git's tracked + untracked non-ignored files.
// Non-Git fallback skips common generated directories; never follows symlinks.
// --map exports [--path <file or dir>] [--max-words N] prints each JavaScript or TypeScript file's exports instead and
// writes nothing (V31-REPO-MAP, specification 3.24): a pattern match over source with comments, strings, templates and
// regular-expression literals blanked, never a parser; names, signature heads and JSDoc first sentences, never values.
import { readFileSync, existsSync, writeFileSync, readdirSync, lstatSync, realpathSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join, relative, basename, sep } from 'node:path';
import { options, sections } from './ledger.mjs';
const args = options(['depth', 'map', 'path', 'max-words']);
const root = args.root, depth = Number(args.depth || 2);
if (args.map !== undefined && args.map !== 'exports') throw Error('--map takes one value: exports');
if (args.map && args.depth !== undefined) throw Error('--depth maps directories; it does not apply to --map exports');
if (!args.map && (args.path !== undefined || args['max-words'] !== undefined)) throw Error('--path and --max-words apply only to --map exports');
if (!Number.isInteger(depth) || depth < 1 || depth > 10) throw Error('--depth must be an integer from 1 to 10');
const out = join(root, 'project', 'structure.md');
const SKIP = new Set(['node_modules', '.git', 'dist', 'build', 'coverage', '.cache', 'project', '.claude', '.codex']);
const eligible = (p) => !p.split('/').some((s) => SKIP.has(s) || s.startsWith('.'));
let files = [], mode = 'Git tracked + untracked, respecting ignores';
try {
  const top = execFileSync('git', ['rev-parse', '--show-toplevel'], { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
  if (realpathSync(root) !== realpathSync(top)) throw Error('not repository root');
  files = execFileSync('git', ['ls-files', '-co', '--exclude-standard', '-z'], { cwd: root, encoding: 'utf8' }).split('\0').filter(Boolean);
} catch (error) {
  if (existsSync(join(root, '.git'))) throw error;
  mode = 'non-Git fallback; common generated and hidden directories excluded';
  const walk = (dir) => {
    for (const ent of readdirSync(dir, { withFileTypes: true })) {
      const p = join(dir, ent.name), rel = relative(root, p).split('\\').join('/');
      if (!eligible(rel) || ent.isSymbolicLink()) continue;
      if (ent.isDirectory()) walk(p); else if (ent.isFile()) files.push(rel);
    }
  };
  walk(root);
}
// Eligible files whose every component exists and none is a symlink: tracked paths must not traverse a replaced directory symlink.
const safeFiles = [...new Set(files)].filter((file) => {
  if (!eligible(file)) return false;
  let p = root;
  for (const part of file.split('/')) { p = join(p, part); if (!existsSync(p) || lstatSync(p).isSymbolicLink()) return false; }
  return true;
});
if (args.map) { exportMap(); process.exit(0); }
const existing = existsSync(out) ? readFileSync(out, 'utf8') : '';
const roles = new Map([...existing.matchAll(/^\| `([^`]+)` \| \d+ \| (.+?) \|$/gm)].map((m) => [m[1], m[2]]));
const kept = sections(existing), counts = new Map([['./', 0]]);
for (const file of safeFiles) {
  const parts = file.split('/');
  if (parts.length === 1) counts.set('./', counts.get('./') + 1);
  for (let d = 1; d < parts.length && d <= depth; d++) {
    const dir = parts.slice(0, d).join('/') + '/'; counts.set(dir, (counts.get(dir) || 0) + 1);
  }
}
const rows = [...counts].sort(([a], [b]) => a.localeCompare(b));
for (const [path] of rows) if (/[|`\r\n]/.test(path)) throw Error(`path cannot be represented in the structure table: ${JSON.stringify(path)}`);
const title = (existing.match(/^# Structure — (.+)$/m) || [, '{project name}'])[1];
const entry = kept.get('Entry points') || '- {file} — {what it starts}';
writeFileSync(out, `# Structure — ${title}\n\n<!-- Generated by tools/structure.mjs. ${mode}. Directory counts include descendants; ./ counts root files only. No symlinks; any existing Where to look first section is not carried forward. -->\n\n| Path | Files | Role |\n| --- | --- | --- |\n${rows.map(([path, count]) => `| \`${path}\` | ${count} | ${roles.get(path) || '{what lives here, one line}'} |`).join('\n')}\n\n## Entry points\n\n${entry}\n`);
console.log(`structure: ${rows.length} rows; ${mode}; roles and entry sections kept`);

// ---- The export map (V31-REPO-MAP). Printed for the reader who asked, never recorded, never in the base read.
function exportMap() {
  const SOURCE = /\.(?:[cm]?[jt]s|[jt]sx)$/, MAX_BYTES = 512 * 1024, MAX_LINE = 2000;
  const maxWords = Number(args['max-words'] ?? 2000);
  if (!Number.isInteger(maxWords) || maxWords < 1 || maxWords > 100000) throw Error('--max-words must be an integer from 1 to 100000');
  const realRoot = realpathSync(root);
  let selected = safeFiles;
  if (args.path !== undefined) {
    const sel = args.path.split('\\').join('/').replace(/^\.\/+/, '').replace(/\/+$/, '');
    if (!sel || sel.startsWith('/') || /^[A-Za-z]:/.test(sel) || sel.split('/').some((s) => s === '..' || s === '.' || s === '')) throw Error(`--path must be a file or directory inside the root, relative to it: ${JSON.stringify(args.path)}`);
    selected = safeFiles.filter((f) => f === sel || f.startsWith(`${sel}/`));
    if (!selected.length) throw Error(`--path names no mapped file: ${JSON.stringify(args.path)}`);
  }
  const shown = (p) => /[\u0000-\u001f\u007f`]/.test(p) ? JSON.stringify(p) : p;
  const words = (s) => (s.match(/\S+/g) || []).length;
  const blocks = [], skipped = [], none = [], approx = [], index = new Map(); let names = 0, mapped = 0;
  for (const file of selected.filter((f) => SOURCE.test(f) && !/\.min\.[cm]?js$/.test(f)).sort()) {
    let buf; // the listing's checks are static; a file must still resolve inside the root when it is read
    try { if (!realpathSync(join(root, file)).startsWith(realRoot + sep)) { skipped.push(`- ${shown(file)} — resolves outside the root`); continue; } buf = readFileSync(join(root, file)); } catch { skipped.push(`- ${shown(file)} — unreadable`); continue; }
    const src = buf.toString('utf8');
    const why = buf.length > MAX_BYTES ? 'over 512 KiB' : buf.includes(0) ? 'holds a NUL byte' : src.split('\n').some((l) => l.length > MAX_LINE) ? 'a line over 2,000 characters' : '';
    if (why) { skipped.push(`- ${shown(file)} — ${why}`); continue; }
    const { found, approximate } = exportsOf(src); mapped++; names += found.length;
    if (approximate) approx.push(file);
    const dir = file.includes('/') ? file.slice(0, file.lastIndexOf('/') + 1) : './';
    const row = index.get(dir) || { files: 0, names: 0, words: 0 };
    row.files++; index.set(dir, row);
    if (!found.length) { none.push(`${shown(file)}${approximate ? ' (approximate)' : ''}`); continue; }
    const block = `## ${shown(file)} — ${found.length}${approximate ? ' (approximate: brackets did not balance)' : ''}\n\n${found.map((e) => `- ${e.line} ${e.sig}${e.doc ? ` — ${e.doc}` : ''}`).join('\n')}\n`;
    blocks.push(block); row.names += found.length; row.words += words(block);
  }
  const title = basename(realpathSync(root));
  const head = `# Exports — ${shown(title)}\n\n<!-- Printed by node tools/structure.mjs --map exports; not a record and not read at start. A pattern match, not a parser: each line is a line number and a signature head, never a value; a string prints as an ellipsis. -->\n`;
  const tail = `${none.length ? `\nNo export found: ${none.join(', ')}.\n` : ''}${skipped.length ? `\n## Skipped\n\n${skipped.join('\n')}\n` : ''}`;
  let body = blocks.join('\n'), end = tail;
  const total = words(head + body + tail), over = total > maxWords;
  if (over) { // the index: every directory with a mapped file, its files, names and the words its part of the map would take
    body = `${total} words, over the cap of ${maxWords}: pass --path <directory or file> to print one area, or a larger --max-words.\n\n| Directory | Files | Names | Words |\n| --- | --- | --- | --- |\n${[...index].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)).map(([d, r]) => `| ${shown(d)} | ${r.files} | ${r.names} | ${r.words} |`).join('\n')}\n`;
    end = skipped.length ? `\n${skipped.length} skipped; --path lists them.\n` : '';
  }
  process.stdout.write(`${head}\n${body}${end}\n`);
  const plural = (k, w) => `${k} ${w}${k === 1 ? '' : 's'}`;
  console.log(`structure: exports of ${plural(mapped, 'file')}, ${plural(names, 'name')}, ${total} words${over ? ', the index printed' : ''}; ${approx.length} approximate, ${skipped.length} skipped; ${mode}; nothing written`);
}

// Blank comments, strings, templates and regular-expression literals to spaces, line breaks kept, so offsets hold.
// A quoted string ends at its line, bounding the damage of a stray quote such as an apostrophe in JSX text.
function blank(src) {
  const out = src.split(''), strings = [], docs = [], n = src.length;
  const WORDS = new Set(['return', 'typeof', 'instanceof', 'in', 'of', 'new', 'delete', 'void', 'throw', 'case', 'do', 'else', 'yield', 'await']);
  const wipe = (a, b) => { for (let k = a; k < b; k++) if (out[k] !== '\n' && out[k] !== '\r') out[k] = ' '; };
  let unterminated = false;
  const before = (k) => { let j = k - 1; while (j >= 0 && /\s/.test(src[j])) j--; const e = j + 1; while (j >= 0 && /[\w$]/.test(src[j])) j--; return src.slice(j + 1, e); };
  const template = (k) => { // from an opening backtick to after its closing one, substitutions scanned as code
    for (k++; k < n;) {
      if (src[k] === '\\') k += 2;
      else if (src[k] === '`') return k + 1;
      else if (src[k] === '$' && src[k + 1] === '{') k = code(k + 2, true);
      else k++;
    }
    unterminated = true; return n;
  };
  function code(k, sub) { // sub: inside a substitution, which ends at its own closing brace
    let depth = 0, prev = ''; const parens = []; // per open parenthesis: does it follow if, while, for or with
    while (k < n) {
      const c = src[k], d = src[k + 1];
      if (c === '/' && d === '/') { const e = src.indexOf('\n', k), end = e < 0 ? n : e; if (!sub) wipe(k, end); k = end; continue; }
      if (c === '/' && d === '*') {
        const e = src.indexOf('*/', k + 2), end = e < 0 ? n : e + 2;
        if (e < 0) unterminated = true;
        if (!sub && src[k + 2] === '*' && src[k + 3] !== '/') docs.push({ end, text: src.slice(k + 3, Math.max(k + 3, end - 2)) });
        if (!sub) wipe(k, end); k = end; continue;
      }
      if (c === '\'' || c === '"') {
        let e = k + 1;
        while (e < n && src[e] !== c && src[e] !== '\n') e += src[e] !== '\\' ? 1 : src[e + 1] === '\r' && src[e + 2] === '\n' ? 3 : 2;
        const closed = src[e] === c, end = Math.min(n, closed ? e + 1 : e);
        if (!sub) { strings.push({ start: k, text: src.slice(k + 1, closed ? e : end) }); wipe(k + 1, closed ? end - 1 : end); }
        prev = 'x'; k = end; continue;
      }
      if (c === '`') { const end = template(k); if (!sub) wipe(k + 1, end - 1); prev = 'x'; k = end; continue; }
      if ((c === '+' || c === '-') && d === c) { prev = prev === 'x' || prev === 'w' ? 'x' : c; k += 2; continue; } // postfix leaves a value
      if (c === '/' && (prev === 'ctl' || '(,=:[!&|?{};+-*%<>~^'.includes(prev) || (prev === 'w' && WORDS.has(before(k))))) {
        let e = k + 1, cls = false;
        while (e < n && src[e] !== '\n') { if (src[e] === '\\') { e += 2; continue; } if (src[e] === '[') cls = true; else if (src[e] === ']') cls = false; else if (src[e] === '/' && !cls) break; e++; }
        if (src[e] === '/') { const shut = e++; while (e < n && /[a-z]/i.test(src[e])) e++; if (!sub) { wipe(k + 1, shut); wipe(shut + 1, e); } prev = 'x'; k = e; continue; }
      }
      if (sub && c === '{') depth++;
      else if (sub && c === '}') { if (depth === 0) return k + 1; depth--; }
      if (c === '(') parens.push(prev === 'w' && ['if', 'while', 'for', 'with'].includes(before(k)));
      if (!/\s/.test(c)) prev = /[\w$]/.test(c) ? (/[0-9]/.test(c) && prev !== 'w' ? 'x' : 'w') : c === ')' ? (parens.pop() ? 'ctl' : 'x') : c === ']' ? 'x' : c;
      k++;
    }
    if (sub) unterminated = true;
    return n;
  }
  code(0, false);
  return { code: out.join(''), strings, docs, unterminated };
}

// Each export of a module, in source order: { line, sig, doc }; approximate when brackets did not balance.
function exportsOf(src) {
  const { code, strings, docs, unterminated } = blank(src);
  const ID = '[\\p{ID_Start}_$][\\p{ID_Continue}$\\u200c\\u200d]*', K = '(?![\\p{ID_Continue}$])', OPEN = '([{', SHUT = ')]}';
  const re = (source, flags = '') => new RegExp(source, `${flags}u`);
  const depth = new Int32Array(code.length + 1); let level = 0, low = 0;
  for (let i = 0; i < code.length; i++) { depth[i] = level; if (OPEN.includes(code[i])) level++; else if (SHUT.includes(code[i])) { level--; low = Math.min(low, level); } }
  const approximate = unterminated || level !== 0 || low < 0;
  const close = (s, i) => { // index after the partner of the bracket at i
    const open = s[i], shut = { '(': ')', '[': ']', '{': '}', '<': '>' }[open]; let k = 0;
    for (let j = i; j < s.length; j++) {
      if (open === '<' && s[j] === '=' && s[j + 1] === '>') { j++; continue; }
      if (s[j] === open) k++; else if (s[j] === shut && --k === 0) return j + 1;
    }
    return s.length;
  };
  const squash = (s) => s.replace(/\s+/g, ' ').replace(/(['"`]) *\1/g, '$1…$1').replace(/\/ +\//g, '/…/').replace(/([([{<]) /g, '$1').replace(/ ([)\]}>,])/g, '$1').trim();
  const cut = (s, max) => s.length > max ? `${s.slice(0, max - 1).trimEnd()}…` : s;
  const split = (s) => { const parts = []; let k = 0, last = 0; for (let j = 0; j < s.length; j++) { if (OPEN.includes(s[j])) k++; else if (SHUT.includes(s[j])) k--; else if (s[j] === ',' && k === 0) { parts.push(s.slice(last, j)); last = j + 1; } } parts.push(s.slice(last)); return parts.map((p) => p.trim()).filter(Boolean); };
  const stringAt = (i) => strings.find((s) => s.start >= i && code.slice(i, s.start).trim() === '');
  const summary = (text) => {
    const body = text.split('\n').map((l) => l.replace(/^\s*\*?\s?/, '')).join('\n').split(/(?:^|\n)\s*@/)[0].replace(/\s+/g, ' ').trim();
    return cut((body.match(/^.*?[.!?](?=\s|$)/) || [body])[0], 100);
  };
  const docBefore = (i) => { // a /** */ block with nothing but decorators between it and i
    let d; for (const x of docs) { if (x.end <= i) d = x; else break; }
    return d && code.slice(d.end, i).replace(/@[\w$.]+(\([^)]*\))?/g, '').trim() === '' ? summary(d.text) : '';
  };
  const atStart = (i) => { let j = i - 1; while (j >= 0 && (code[j] === ' ' || code[j] === '\t')) j--; return j < 0 || ';\n\r}'.includes(code[j]); };
  const lineOf = (() => { const starts = [0]; for (let i = 0; i < code.length; i++) if (code[i] === '\n') starts.push(i + 1); return (at) => { let lo = 0, hi = starts.length - 1; while (lo < hi) { const mid = (lo + hi + 1) >> 1; if (starts[mid] <= at) lo = mid; else hi = mid - 1; } return lo + 1; }; })();
  const entry = (sig, at, docAt = at) => ({ line: lineOf(at), sig: cut(squash(sig), 120), doc: docBefore(docAt) });
  // From just after a name: generic parameters, the parameter list and a TypeScript return type.
  const params = (i) => {
    let j = i; while (/\s/.test(code[j])) j++;
    if (code[j] === '<') { j = close(code, j); while (/\s/.test(code[j])) j++; }
    if (code[j] !== '(') return code.slice(i, i);
    let e = close(code, j), k = e; while (/[ \t]/.test(code[k])) k++;
    if (code[k] === ':') {
      let t = k + 1, d = 0;
      for (; t < code.length; t++) {
        const c = code[t];
        if ('([<'.includes(c)) d++;
        else if (')]'.includes(c) || (c === '>' && code[t - 1] !== '=')) d--;
        else if (c === '{') { const so = code.slice(k + 1, t).trim(); if (d === 0 && so && !/[:|&,<(=>]$/.test(so)) break; t = close(code, t) - 1; }
        else if (d === 0 && (c === ';' || c === '\n' || (c === '=' && code[t + 1] === '>'))) break;
      }
      e = t;
    }
    return code.slice(i, e);
  };
  // A statement's end: a ; at its depth, a closing bracket of an outer one, or a line end the next line does not continue.
  const statementEnd = (i) => {
    let k = 0;
    for (let j = i; j < code.length; j++) {
      const c = code[j];
      if (OPEN.includes(c)) k++;
      else if (SHUT.includes(c)) { if (k === 0) return j; k--; }
      else if (k === 0 && c === ';') return j;
      else if (k === 0 && c === '\n') {
        let b = j - 1; while (b >= i && /\s/.test(code[b])) b--;
        const a = code.slice(j, j + 400).trimStart();
        if (!(b >= i && ',=+-*/%&|^!?:<>.('.includes(code[b])) && !/^[,.?:+\-*/%&|^=)\]}>]/.test(a) && !/^(as|satisfies|extends|implements)\b/.test(a)) return j;
      }
    }
    return code.length;
  };
  // A declaration at p, exported or not: a list of { name, sig }, or null when p starts none.
  const declaration = (p) => {
    const t = code.slice(p); let r;
    if ((r = t.match(re(`^(?:declare\\s+)?(async\\s+)?function${K}\\s*(\\*)?\\s*(${ID})`)))) return [{ name: r[3], sig: `${r[1] ? 'async ' : ''}function${r[2] || ''} ${r[3]}${params(p + r[0].length)}` }];
    if ((r = t.match(re(`^(?:declare\\s+)?(abstract\\s+)?class${K}\\s*(${ID})([^{]*)`)))) return [{ name: r[2], sig: `${r[1] ? 'abstract ' : ''}class ${r[2]}${r[3]}` }];
    if ((r = t.match(re(`^(?:declare\\s+)?interface\\s+(${ID})([^{]*)`)))) return [{ name: r[1], sig: `interface ${r[1]}${r[2]}` }];
    if ((r = t.match(re(`^(?:declare\\s+)?type\\s+(${ID})\\s*`)))) {
      let e = p + r[0].length; const g = code[e] === '<' ? code.slice(e, (e = close(code, e))) : '';
      if (/^\s*=(?!=)/.test(code.slice(e))) return [{ name: r[1], sig: `type ${r[1]}${g}` }];
    }
    if ((r = t.match(re(`^(?:declare\\s+)?(const\\s+)?enum\\s+(${ID})`)))) return [{ name: r[2], sig: `${r[1] ? 'const ' : ''}enum ${r[2]}` }];
    if ((r = t.match(re(`^(?:declare\\s+)?(?:namespace|module)\\s+(${ID}(?:\\.${ID})*)`)))) return [{ name: r[1], sig: `namespace ${r[1]}` }];
    if ((r = t.match(/^(?:declare\s+)?(const|let|var|using)\s+/))) return declarators(r[1], p + r[0].length);
    return null;
  };
  // A TypeScript type from i: brackets and angle brackets balanced, ending at a depth-0 =, a comma or the end, or at
  // a depth-0 => when stopAtArrow; an arrow's > never closes an angle bracket.
  const typeEnd = (s, i, stopAtArrow = false) => {
    let d = 0;
    for (; i < s.length; i++) {
      const c = s[i], arrow = c === '=' && s[i + 1] === '>';
      if (arrow) { if (d === 0 && stopAtArrow) return i; i++; continue; }
      if ('([{<'.includes(c)) d++;
      else if (')]}>'.includes(c)) { if (d === 0) return i; d--; }
      else if (d === 0 && (c === '=' || c === ',')) return i;
    }
    return s.length;
  };
  // Declarators split at depth-0 commas, a type annotation's angle brackets kept whole.
  const declSplit = (s) => {
    const parts = []; let last = 0;
    for (let j = 0; j < s.length; j++) {
      if (OPEN.includes(s[j])) { j = close(s, j) - 1; continue; }
      if (s[j] === ':') { j = typeEnd(s, j + 1) - 1; continue; }
      if (s[j] === ',') { parts.push(s.slice(last, j)); last = j + 1; }
    }
    parts.push(s.slice(last)); return parts.map((x) => x.trim()).filter(Boolean);
  };
  // An arrow function's whole head — a balanced parameter list and an optional return type, or one name — else null.
  const arrowHead = (init) => {
    const a = init.match(/^async\s+/), h = init.slice(a ? a[0].length : 0);
    let e;
    if (h[0] === '(') {
      e = close(h, 0); let k = e; while (/\s/.test(h[k])) k++;
      if (h[k] === ':') { k = typeEnd(h, k + 1, true); }
      if (h.slice(k, k + 2) !== '=>') return null;
      return `${a ? 'async ' : ''}${h.slice(0, k).trim()}`;
    }
    const m = h.match(re(`^(${ID})\\s*=>`));
    return m ? `${a ? 'async ' : ''}${m[1]}` : null;
  };
  const declarators = (kw, start) => {
    const found = [];
    for (const part of declSplit(code.slice(start, statementEnd(start)))) {
      let q, a;
      if (/^[{[]/.test(part)) { // a destructuring pattern: identifiers not followed by a colon, defaults dropped
        const inner = part.slice(1, close(part, 0) - 1).replace(/=[^,}\]]*/g, '');
        for (const m of inner.matchAll(re(`(?:\\.\\.\\.)?(${ID})\\s*(?=[,}\\]]|$)`, 'g'))) found.push({ name: m[1], sig: `${kw} ${m[1]}` });
        continue;
      }
      if (!(q = part.match(re(`^(${ID})!?\\s*`)))) continue;
      const name = q[1]; let j = q[0].length, type = '';
      if (part[j] === ':') { const t = typeEnd(part, j + 1); type = part.slice(j, t); j = t; }
      const typed = `${kw} ${name}${type ? squash(type) : ''}`;
      const init = part[j] === '=' ? part.slice(j + 1).trim() : '', head = init && arrowHead(init);
      if (head) found.push({ name, sig: `${typed} = ${head} =>` });
      else if ((a = init.match(re(`^(async\\s+)?function${K}\\s*(\\*)?\\s*(?:${ID})?\\s*`))) && init[a[0].length] === '(') found.push({ name, sig: `${typed} = ${a[1] ? 'async ' : ''}function${a[2] || ''}${init.slice(a[0].length, close(init, a[0].length))}` });
      else if (re(`^class${K}`).test(init)) found.push({ name, sig: `${typed} = class` });
      else found.push({ name, sig: typed });
    }
    return found;
  };
  // Top-level declarations by name, for an export list without a source.
  const local = new Map();
  for (const m of code.matchAll(/\b(export\s+(?:default\s+)?)?(?:declare\s+)?(?:async\s+)?(?:function|class|abstract|interface|type|enum|namespace|const|let|var)\b/g)) {
    if (depth[m.index] !== 0 || code[m.index - 1] === '.' || !atStart(m.index)) continue;
    for (const d of declaration(m.index + (m[1] || '').length) || []) if (!local.has(d.name)) local.set(d.name, { ...d, at: m.index });
  }
  const found = [];
  for (const m of code.matchAll(/\b(?:export|module\.exports|exports)\b/g)) {
    const at = m.index, word = m[0];
    if (depth[at] !== 0 || code[at - 1] === '.' || !atStart(at)) continue;
    if (word !== 'export') { commonjs(at); continue; }
    const after = at + 6, rest = code.slice(after); let r;
    if ((r = rest.match(/^\s+default(?![\p{ID_Continue}$])\s*/u))) {
      const p = after + r[0].length, t = code.slice(p); let q;
      if ((q = t.match(re(`^(async\\s+)?function${K}\\s*(\\*)?\\s*(${ID})?`)))) found.push(entry(`default ${q[1] ? 'async ' : ''}function${q[2] || ''}${q[3] ? ` ${q[3]}` : ''}${params(p + q[0].length)}`, at));
      else if ((q = t.match(re(`^(abstract\\s+)?class\\b\\s*(?!(?:extends|implements)\\b)(${ID})?([^{]*)`)))) found.push(entry(`default ${q[1] ? 'abstract ' : ''}class${q[2] ? ` ${q[2]}` : ''}${q[3]}`, at));
      else if ((q = t.match(re(`^interface\\s+(${ID})([^{]*)`)))) found.push(entry(`default interface ${q[1]}${q[2]}`, at));
      else if ((q = t.match(re(`^(${ID})\\s*(;|\\n|$)`)))) found.push(entry(`default ${q[1]}`, at, local.get(q[1])?.at ?? at));
      else found.push(entry('default (expression)', at));
      continue;
    }
    if ((r = rest.match(/^\s+/)) && declaration(after + r[0].length)) { for (const d of declaration(after + r[0].length)) found.push(entry(d.sig, at)); continue; }
    if ((r = rest.match(re(`^\\s*=\\s*(${ID})?`)))) { found.push(entry(`export = ${r[1] || '(expression)'}`, at)); continue; }
    if ((r = rest.match(re(`^\\s+import\\s+(${ID})\\s*=`)))) { found.push(entry(`import ${r[1]} =`, at)); continue; }
    if ((r = rest.match(re(`^\\s+as\\s+namespace\\s+(${ID})`)))) { found.push(entry(`as namespace ${r[1]}`, at)); continue; }
    if ((r = rest.match(re(`^\\s*(type\\s+)?\\*\\s*(?:as\\s+(${ID})\\s+)?from\\s*`)))) { const s = stringAt(after + r[0].length); found.push(entry(`${r[1] ? 'type ' : ''}*${r[2] ? ` as ${r[2]}` : ''} from '${s ? s.text : '?'}'`, at)); continue; }
    if ((r = rest.match(/^\s*(type\s+)?\{/))) {
      const open = after + r[0].length - 1, end = close(code, open);
      const tail = code.slice(end).match(/^\s*from\s*/), s = tail && stringAt(end + tail[0].length);
      for (const part of split(code.slice(open + 1, end - 1))) {
        const pm = part.match(re(`^(type\\s+)?(${ID})(?:\\s+as\\s+(${ID}))?$`));
        if (!pm) { found.push(entry(`${part.replace(/(['"])\s*\1/g, '$1…$1')}${s ? ` from '${s.text}'` : ''}`, at)); continue; }
        const type = r[1] || pm[1] ? 'type ' : '', alias = pm[3] ? ` as ${pm[3]}` : '';
        const own = !s && local.get(pm[2]);
        found.push(own ? entry(`${own.sig}${pm[3] ? `, exported as ${pm[3]}` : ''}`, at, own.at) : entry(`${type}${pm[2]}${alias}${s ? ` from '${s.text}'` : ''}`, at));
      }
    }
  }
  // CommonJS: module.exports = …, exports.name = … and module.exports.name = …, assignments only.
  function commonjs(at) {
    const t = code.slice(at); let q, w;
    if ((q = t.match(/^module\.exports\s*=(?!=)\s*/))) {
      const p = at + q[0].length, v = code.slice(p);
      if (v[0] === '{') {
        for (const part of split(code.slice(p + 1, close(code, p) - 1))) {
          const pm = part.match(re(`^(?:async\\s+)?(${ID})\\s*(\\(|:|$)`));
          if (pm) found.push(entry(`module.exports.${pm[1]}${pm[2] === '(' ? part.slice(pm[0].length - 1, close(part, pm[0].length - 1)) : ''}`, at));
        }
      } else if ((w = v.match(re(`^(async\\s+)?function${K}\\s*(${ID})?`)))) found.push(entry(`module.exports = ${w[1] ? 'async ' : ''}function${w[2] ? ` ${w[2]}` : ''}${params(p + w[0].length)}`, at));
      else if ((w = v.match(re(`^class\\b\\s*(${ID})?`)))) found.push(entry(`module.exports = class${w[1] ? ` ${w[1]}` : ''}`, at));
      else if ((w = v.match(re(`^(${ID})\\s*(;|\\n|$)`)))) found.push(entry(`module.exports = ${local.get(w[1])?.sig ?? w[1]}`, at, local.get(w[1])?.at ?? at));
      else found.push(entry('module.exports = (expression)', at));
      return;
    }
    if ((q = t.match(re(`^(?:module\\.)?exports\\.(${ID})\\s*=(?!=)\\s*`)))) {
      const p = at + q[0].length, v = code.slice(p);
      if ((w = v.match(re(`^(async\\s+)?function${K}\\s*(?:${ID})?`)))) found.push(entry(`exports.${q[1]} = ${w[1] ? 'async ' : ''}function${params(p + w[0].length)}`, at));
      else if ((w = v.match(re(`^(async\\s+)?(\\([^)]*\\)|${ID})\\s*=>`)))) found.push(entry(`exports.${q[1]} = ${w[1] || ''}${w[2]} =>`, at));
      else found.push(entry(`exports.${q[1]}`, at));
    }
  }
  return { found, approximate };
}
